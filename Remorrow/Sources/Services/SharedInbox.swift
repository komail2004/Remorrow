import Foundation

enum SharedInboxError: Error {
    case invalidPayload
    case unavailable
}

/// The extension writes atomically. The main app consumes on launch or foreground.
enum SharedInbox {
    static let groupID = "group.com.komail.Remorrow"

    struct Payload: Codable {
        let id: String
        let type: String
        let text: String?
        let imageFile: String?
        let createdAt: Date
    }

    struct Pending {
        let payload: Payload
        let manifestURL: URL
        let imageURL: URL?
        let imageData: Data?
    }

    static func loadOldest() throws -> Pending? {
        guard let base = FileManager.default.containerURL(forSecurityApplicationGroupIdentifier: groupID) else {
            return nil // No shared container available in unprovisioned previews.
        }
        let folder = base.appendingPathComponent("Inbox", isDirectory: true)
        guard FileManager.default.fileExists(atPath: folder.path) else { return nil }
        let files = try FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: nil)
            .filter { $0.pathExtension == "json" }
            .sorted {
                let lhs = (try? $0.resourceValues(forKeys: [.creationDateKey]).creationDate) ?? .distantFuture
                let rhs = (try? $1.resourceValues(forKeys: [.creationDateKey]).creationDate) ?? .distantFuture
                return lhs == rhs ? $0.lastPathComponent < $1.lastPathComponent : lhs < rhs
            }
        guard let manifest = files.first else { return nil }
        let payload = try JSONDecoder().decode(Payload.self, from: Data(contentsOf: manifest))
        // Do not trust manifest filenames, even though generated by our extension.
        let imageURL: URL?
        if let name = payload.imageFile,
           name == URL(fileURLWithPath: name).lastPathComponent {
            imageURL = folder.appendingPathComponent(name)
        } else {
            imageURL = nil
        }
        let imageData = try imageURL.map { try Data(contentsOf: $0) }
        return Pending(payload: payload, manifestURL: manifest, imageURL: imageURL, imageData: imageData)
    }

    static func remove(_ item: Pending) throws {
        try FileManager.default.removeItem(at: item.manifestURL)
        if let url = item.imageURL { try? FileManager.default.removeItem(at: url) }
    }
}
